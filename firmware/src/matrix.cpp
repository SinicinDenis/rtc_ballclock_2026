int BallMatrix::ledXY(int x, int y) {
    switch (db[kk::reverse_matrix].toInt()) {
        // none
        case 0:
            if (x < 0 || y < 0 || x >= MX_XY_W || y >= MX_XY_H) return -1;
            return ((y & 1) ? 0 : xyToLed[y >> 1][x]) - 1;
            break;
        case 1:
            if (x < 0 || y < 0 || x >= MX_XY_W || y >= MX_XY_H) return -1;
            return ((y & 1) ? 0 : xyToLed1[y >> 1][x]) - 1; 
            break;
        case 2:
            if (x < 0 || y < 0 || x >= MX_XY_W || y >= MX_XY_H) return -1;
            return ((y & 1) ? 0 : xyToLed1[y >> 1][x]) - 1; 
            break;
        case 3:
            if (x < 0 || y < 0 || x >= MX_XY_W || y >= MX_XY_H) return -1;
            return ((y & 1) ? 0 : xyToLed1[y >> 1][x]) - 1; 
            break;
    }
    return -1;
}

int BallMatrix::ledDiag(int x, int y) {
    switch (db[kk::reverse_matrix].toInt()) {
        // none
        case 0:
            if (x < 0 || y < 0 || x >= MX_DIAG_W || y >= MX_DIAG_H) return -1;
            return diagToLed[y][x] - 1;
            break;
        case 1:
            if (x < 0 || y < 0 || x >= MX_DIAG_W || y >= MX_DIAG_H) return -1;
            return diagToLed1[y][x] - 1;
            break;
        case 2:
            if (x < 0 || y < 0 || x >= 7 || y >= 20) return -1;
            return diagToLed2[y][x] - 1;
            break;
        case 3:
            if (x < 0 || y < 0 || x >= 7 || y >= 20) return -1;
            return diagToLed3[y][x] - 1;
            break;
    } 
    return -1;
}

